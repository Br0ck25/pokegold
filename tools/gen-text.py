#!/usr/bin/env python3
"""Generate src/game/data/text.js: all of Gold's map text for the maps in tools/gen-terrain.py BUILT (never retype it from memory).
Game.text[GoldMap][Label] = [paragraph, ...]; `{PLAYER}` and `{RIVAL}` stand for the names (s.text fills them in).
Renames and our own fixes (Willow is a woman, nets instead of balls, ...) are applied here, so the generated file is what the game says;
add a fix to FIXES below instead of editing text.js. Run after adding a map to BUILT:  python3 tools/gen-text.py"""
import importlib.util, json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))

def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(here, name.replace("_", "-") + ".py")) if name != "goldtext" else importlib.util.spec_from_file_location("goldtext", os.path.join(here, "goldtext.py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
sys.argv = [sys.argv[0]]
goldtext = load("goldtext")
BUILT = load("gen_terrain").BUILT

# Global replacements (after goldtext's own Elm/Oak renames): our world's words.
GLOBAL = [("BUDDY BALLS", "BUDDY NETS"), ("BUDDY BALL", "BUDDY NET"), ("<PLAYER>", "{PLAYER}"), ("<RIVAL>", "{RIVAL}"), ("<……>", "……"), ("MR.CHRONO", "MR. CHRONO"),
          ("BUDDYMON GEAR", "BUDDYGEAR"), ("ANTIDOTE", "REMEDY"), ("POTION", "TONIC")]
# Per label: Willow is a woman here, so lines about her change pronouns. {label: [(find, replace)]}
FIXES = {
    "ElmsLookingForYouText": [("He said he wanted you to do something for him.", "She said she wanted you to do something for her."), ("Your BUDDYMON GEAR is back", "Your BUDDYGEAR is back")],
    "PlayersNeighborsDaughterText": [("PIKACHU", "FLUTTERBY"), ("He's so famous", "She's so famous"), ("like him", "like her")],
    "ElmsWifeText": [("My husband's always so busy--I hope he's OK.", "My wife's always so busy--I hope she's OK."), ("When he's caught up in his BUDDYMON research, he even forgets to eat.", "When she's caught up in her BUDDYMON research, she even forgets to eat.")],
    "ElmsSonText": [("my Dad", "my Mom")],
    "MysticWaterGuyTextBefore": [("MYSTIC WATER", "TIDE CHARM")],
    "MomGivesPokegearText": [("BUDDYMON GEAR, or just BUDDYGEAR.", "BUDDYGEAR, or just GEAR.")],
}

def fix(label, text):
    for a, b in GLOBAL: text = text.replace(a, b)
    for a, b in FIXES.get(label, []): text = text.replace(a, b)
    return text

out, mv = {}, {}
for gold in BUILT:
    d = goldtext.parse(gold)
    out[gold] = {lab: [fix(lab, p) for p in ps] for lab, ps in d["texts"].items()}
    if d["moves"]: mv[gold] = d["moves"]
js = "// Gold's map text, generated by tools/gen-text.py from the disassembly (do not edit; add fixes to the tool). Game.text[GoldMap][Label] = [paragraphs]; {PLAYER} {RIVAL} are filled by s.text.\n"
js += "Game.text = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
js += "// Gold's movement scripts as direction lists (0 down, 1 up, 2 left, 3 right; \"tN\" = turn to face N): Game.moves[GoldMap][Label]\nGame.moves = " + json.dumps(mv, separators=(",", ":")) + ";\n"
open(os.path.join(here, "..", "src", "game", "data", "text.js"), "w").write(js)
print(f"{sum(len(v) for m in out.values() for v in m.values())} paragraphs in {len(out)} maps")
