#!/usr/bin/env python3
"""Generate src/game/data/terrain.js from the Gold snapshots in tools/gold/*.json (run after tools/goldmap.py --json updates a snapshot).
BUILT below is the one list of Gold maps we have built and their native keys: add a map there, snapshot it, regenerate.
Outdoor maps: {cols, rows, cells, buildings, signs, warps, exits}; indoor maps: {cols, rows, solid, warps}. Native map files never hand-copy these.
  cells: . floor, p dirt road leading off a connected map edge, S free-standing sign, T wall/tree, g tall grass, w water, v > < R L ledge cells (walkable: jump 2 cells their way), C cliff face
  buildings: Gold's footprints [{x, y, w, h, doors: [[x, y]]}] (cleared to floor in cells; the engine draws them)
  warps: doors/mats {x, y, to: native key or null (not built yet), toConst, tx, ty, dir}: where you arrive (on the matching door tile, facing away, as in Gold)
  exits: floor cells on connected map edges {x, y, side, to, tx, ty, dir}: the same for map-to-map roads
  solid: '#' blocked, '.' walkable (door carpets walkable)"""
import json, os

BUILT = {
    "DarkCaveVioletEntrance": "darkcave",
    "PlayersHouse2F": "bedroom", "PlayersHouse1F": "livingroom", "NewBarkTown": "newbark", "ElmsLab": "willowlab", "PlayersNeighborsHouse": "neighbor",
    "ElmsHouse": "willowhouse", "Route29": "route29", "Route29Route46Gate": "gate29", "CherrygroveCity": "cherrygrove", "CherrygroveMart": "cgmart",
    "CherrygrovePokecenter1F": "cgcenter", "GuideGentsHouse": "cggent", "CherrygroveGymSpeechHouse": "cggym", "CherrygroveEvolutionSpeechHouse": "cgevo",
    "Route30": "route30", "MrPokemonsHouse": "mrbuddy", "Route31": "route31", "Route31VioletGate": "gate31", "VioletCity": "violet", "VioletMart": "vmart",
    "VioletPokecenter1F": "vcenter", "VioletNicknameSpeechHouse": "vnickname", "EarlsPokemonAcademy": "academy", "VioletGym": "violetgym",
}
OUTDOOR = ["DarkCaveVioletEntrance", "NewBarkTown", "Route29", "CherrygroveCity", "Route30", "Route31", "VioletCity"]
here = os.path.dirname(__file__)
SNAP = {}
for n in BUILT:
    SNAP[n] = json.load(open(os.path.join(here, "gold", n + ".json")))
BY_CONST = {g["const"]: g for g in SNAP.values()}

def arrival(g, wp):
    """Where you stand after coming through this door of map g: the first free cell beside it, facing away from it."""
    W, H = g["w"], g["h"]
    x, y = wp["x"], wp["y"]
    doors = {(w["x"], w["y"]) for w in g["warps"]}
    order = {"bottom": [(0, -1, 1), (1, 0, 3), (-1, 0, 2)], "top": [(0, 1, 0), (1, 0, 3), (-1, 0, 2)], "left": [(1, 0, 3), (0, 1, 0), (0, -1, 1)], "right": [(-1, 0, 2), (0, 1, 0), (0, -1, 1)]}
    edge = "bottom" if y == H - 1 and g["tileset"] not in ("johto", "kanto") else "top" if y == 0 and g["tileset"] not in ("johto", "kanto") else "left" if x == 0 and g["tileset"] not in ("johto", "kanto") else "right" if x == W - 1 and g["tileset"] not in ("johto", "kanto") else None
    cands = order[edge] if edge else [(0, 1, 0), (1, 0, 3), (-1, 0, 2), (0, -1, 1)]
    for dx, dy, d in cands:
        cx, cy = x + dx, y + dy
        if 0 <= cx < W and 0 <= cy < H and g["grid"][cy][cx] in ".gv" and (cx, cy) not in doors:
            return cx, cy, d
    return None

def warp_entry(g, wp):
    target = BY_CONST.get(wp["to"])
    e = dict(x=wp["x"], y=wp["y"], toConst=wp["to"], to=None, tx=None, ty=None, dir=None)
    if target and target["name"] in BUILT and 0 < wp["idx"] <= len(target["warps"]):
        dest = target["warps"][wp["idx"] - 1]
        a = arrival(target, dest)
        # Gold puts you ON the matching door tile, facing away from it (so its scripted walks start from there)
        if a: e.update(to=BUILT[target["name"]], tx=dest["x"], ty=dest["y"], dir=a[2])
    return e

out = ["// Generated by tools/gen-terrain.py from tools/gold/*.json (Gold's real maps). Do not edit; change the snapshot or the generator.", "Game.terrain = {};"]
for n, g in SNAP.items():
    W, H = g["w"], g["h"]
    entry = dict(cols=W, rows=H, warps=[warp_entry(g, w) for w in g["warps"]], key=BUILT[n])
    if n in OUTDOOR:
        cells = [[c if c in ".gwvc<>RLo" else "T" for c in r] for r in g["grid"]]
        # the wall square a ledge is jumped over is its cliff face
        ahead = {"v": [(0, 1)], ">": [(1, 0)], "<": [(-1, 0)], "R": [(0, 1), (1, 0)], "L": [(0, 1), (-1, 0)]}
        for y in range(H):
            for x in range(W):
                for dx, dy in ahead.get(cells[y][x], []):
                    if 0 <= x + dx < W and 0 <= y + dy < H and cells[y + dy][x + dx] in "To": cells[y + dy][x + dx] = "C"
        cells = [["r" if c == "o" else c for c in r] for r in cells]
        for b in g["buildings"]:
            for y in range(b["y"], b["y"] + b["h"]):
                for x in range(b["x"], b["x"] + b["w"]): cells[y][x] = "."
        for wp in g["warps"]: cells[wp["y"]][wp["x"]] = "."
        inside = lambda s: any(b["x"] <= s["x"] < b["x"] + b["w"] and b["y"] <= s["y"] < b["y"] + b["h"] for b in g["buildings"])
        signs = [[s["x"], s["y"]] for s in g["signs"] if s["kind"] == "BGEVENT_READ" and not inside(s)]
        for x, y in signs: cells[y][x] = "S"
        # only edges you can actually walk to from a door count (Gold also draws floor pockets that belong to the neighbouring map)
        HOP = {"v": [(0, 1)], ">": [(1, 0)], "<": [(-1, 0)], "R": [(0, 1), (1, 0)], "L": [(0, 1), (-1, 0)]}
        free = lambda x, y: 0 <= x < W and 0 <= y < H and cells[y][x] in ".gvc<>RL"[:0] + ".gp<>vRL"
        seeds = [(w["x"], w["y"]) for w in g["warps"]]
        reach, stack = set(), list(seeds)
        while stack:
            x, y = stack.pop()
            if (x, y) in reach: continue
            reach.add((x, y))
            nxt = [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)] + [(x + 2 * dx, y + 2 * dy) for dx, dy in HOP.get(cells[y][x], [])]
            stack += [(a, b) for a, b in nxt if free(a, b) or (0 <= a < W and 0 <= b < H and cells[b][a] == "g")]
        exits = []
        for side, to, off in g["connections"]:
            o = int(off) * 2
            tg = SNAP.get(to)
            edge = {"north": [(x, 0) for x in range(W)], "south": [(x, H - 1) for x in range(W)], "west": [(0, y) for y in range(H)], "east": [(W - 1, y) for y in range(H)]}[side]
            for x, y in edge:
                if g["grid"][y][x] != "." or (x, y) not in reach: continue
                e = dict(x=x, y=y, side=side, toName=to, to=None, tx=None, ty=None, dir={"north": 1, "south": 0, "west": 2, "east": 3}[side])
                if tg:
                    if side in ("north", "south"): nx, ny = x - o, (tg["h"] - 1 if side == "north" else 0)
                    else: nx, ny = (tg["w"] - 1 if side == "west" else 0), y - o
                    ax, ay = {"north": (nx, ny - 1), "south": (nx, ny + 1), "west": (nx - 1, ny), "east": (nx + 1, ny)}[side]
                    if all(0 <= c < lim and tg["grid"][cy][cx] in "." for c, lim, cx, cy in [(ax, tg["w"], ax, ay), (ay, tg["h"], ax, ay)]) and tg["grid"][ny][nx] == ".":
                        e.update(to=BUILT[to], tx=ax, ty=ay)
                    else: continue  # the neighbour is a wall here in Gold too: a dead end, no road and no exit
                exits.append(e)
                for k in range(0, 4):  # a road leading out: the edge cell and up to 3 floor cells inward
                    cx, cy = {"north": (x, k), "south": (x, H - 1 - k), "west": (k, y), "east": (W - 1 - k, y)}[side]
                    if cells[cy][cx] == ".": cells[cy][cx] = "p"
                    else: break
        entry.update(cells=["".join(r) for r in cells], signs=signs, exits=exits,
                     buildings=[dict(x=b["x"], y=b["y"], w=b["w"], h=b["h"], doors=[[d[0], d[1]] for d in b["doors"]]) for b in g["buildings"]])
    else:
        solid = [["." if c in ".gwvD" and False or c in ".gwv" else "#" for c in r] for r in g["grid"]]
        for wp in g["warps"]: solid[wp["y"]][wp["x"]] = "."
        entry["solid"] = ["".join(r) for r in solid]
        entry["kinds"] = g["grid"]  # furniture kinds for the generic room art
        entry["props"] = [[sg["x"], sg["y"], sg["script"]] for sg in g["signs"]] + [[o["x"], o["y"], o["sprite"]] for o in g["objects"] if o["move"] == "STILL"]
    out.append(f"Game.terrain.{n} = {json.dumps(entry, separators=(',', ':'))};")
path = os.path.join(here, "..", "src", "game", "data", "terrain.js")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path))
