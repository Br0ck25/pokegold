#!/usr/bin/env node
// Builds worker.js, the one file you paste into the Cloudflare dashboard (the page is embedded in it).
// Also rewrites MAP.md, the index of every source file. Usage: node build.js
// Rules enforced here: every source file stays under MAX_LINES; every file starts with a `//` or `/*` header line (it feeds MAP.md).
const fs = require("fs");
const path = require("path");

const MAX_LINES = 2000;
const src = path.join(__dirname, "src");
const read = (f) => fs.readFileSync(path.join(src, f), "utf8");

// Page bundle order: registry (globals) first, then shared UI, art, scenes, the HD core, then the game engine (core, lib, data, battle,
// menus) and last the map files, which register themselves with Game and may use anything loaded before them.
const hdOrder = ["page/hd/core/registry.js", "page/hd/ui", "page/hd/art", "page/hd/scenes", "page/hd/core", "game/core.js", "game/lib", "game/data", "game/battle", "game/menu", "game"];
const walk = (rel, ext, seen) => {
  const abs = path.join(src, rel);
  if (!fs.existsSync(abs)) return [];
  if (!fs.statSync(abs).isDirectory()) return abs.endsWith(ext) && !seen.has(rel) ? (seen.add(rel), [rel]) : [];
  return fs.readdirSync(abs).sort().flatMap((f) => walk(path.posix.join(rel, f), ext, seen));
};
// A css file marked `/*wide*/` gets a copy of its cqw rules in cqh for wide stages (landscape phone): there the stage is as short as a portrait one is
// narrow, so the same sizes measured against the height look right.
const wide = (text) => {
  if (!text.includes("/*wide*/")) return text;
  const plain = text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/@keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*\s*\}/g, "");
  const rules = [...plain.matchAll(/([^{}]+)\{([^{}]*cqw[^{}]*)\}/g)].map((m) => `${m[1].trim()} {${m[2].replace(/cqw/g, "cqh")}}`);
  return `${text}\n@container (min-aspect-ratio: 11/10) {\n${rules.join("\n")}\n}\n`;
};
const bundle = (ext, tail) => {
  const seen = new Set();
  const files = [...hdOrder, ...tail].flatMap((e) => walk(e, ext, seen));
  return { files, text: files.map((f) => `/* ${f} */\n${ext === ".css" ? wide(read(f)) : read(f)}`).join("\n") };
};

const js = bundle(".js", ["page/app.js", "page/pad.js"]);
const css = bundle(".css", ["page/style.css"]);
const embedded = {
  "/index.html": read("page/index.html"),
  "/app.js": '"use strict";\n' + js.text,
  "/style.css": css.text,
  "/manifest.json": read("page/manifest.json"),
};
// PWA: icons (base64) and a service worker whose cache version changes whenever the shell does.
for (const f of fs.readdirSync(path.join(src, "page/icons"))) embedded["/" + f] = fs.readFileSync(path.join(src, "page/icons", f)).toString("base64");
const version = require("crypto").createHash("sha1").update(embedded["/index.html"] + embedded["/app.js"] + embedded["/style.css"]).digest("hex").slice(0, 10);
embedded["/sw.js"] = read("page/sw.js").replace("__VERSION__", version);

// Index of all source files for MAP.md, plus the size rule.
const all = [...new Set([...js.files, ...css.files, "page/index.html", "page/sw.js", "worker/index.js"])].sort();
const rows = all.map((f) => {
  const text = read(f), lines = text.split("\n").length;
  if (lines > MAX_LINES) throw new Error(`${f} has ${lines} lines (max ${MAX_LINES})`);
  const first = text.split("\n").find((l) => l.trim()) || "";
  const note = first.replace(/^\s*(\/\/|\/\*|<!--)\s*/, "").replace(/\s*(\*\/|-->)\s*$/, "");
  if (/^game\/[a-z0-9]+\.js$/.test(f) && /Game\.(register|outdoor|indoor)\(/.test(text) && !/^\/\/ Gold: .+\.asm/m.test(text.split("\n").slice(0, 6).join("\n"))) throw new Error(`${f} registers a map but has no "// Gold: <Map>.asm" line in its header: read Gold's map first`);
  if (!/^\s*(\/\/|\/\*|<!--)/.test(first) && f !== "page/index.html") throw new Error(`${f} needs a header comment on its first line`);
  return `| \`src/${f}\` | ${lines} | ${note} |`;
});
fs.writeFileSync(path.join(__dirname, "MAP.md"), `# Code map (generated by \`node build.js\`; do not edit)\n\nEvery source file, its size and its first-line description. Add a header comment to every new file.\n\n| File | Lines | What it is |\n|---|---|---|\n${rows.join("\n")}\n| \`src/page/manifest.json\` | - | PWA manifest (name, icons, standalone display) |\n| \`src/page/icons/*.png\` | - | App icons, drawn by \`tools/make-icons.js\` |\n`);

const out = path.join(__dirname, "worker.js");
fs.writeFileSync(out, `const EMBEDDED = ${JSON.stringify(embedded)};\n\n${read("worker/index.js")}`);
console.log(`worker.js: ${(fs.statSync(out).size / 1e3).toFixed(0)} KB, ${all.length} source files`);
